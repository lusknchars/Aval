/**
 * The verdict: the output boundary of the evaluation layer.
 *
 * There is no numeric score here, on purpose. A weighted sum is impossible to
 * explain to an auditor and impossible to calibrate with confidence. Findings
 * combine by SEVERITY CEILING, and every decision traces back to a named
 * finding and a specific rule.
 */
import { z } from "zod";

/** Which check produced the finding. */
export const checkKindSchema = z.enum([
  "undeclared", // A -- effect the manifest does not allow
  "magnitude", // B -- amount diverges from what the tool call declared
  "provenance", // C -- origin of the counterparty
  "scope", // permitted effect, on an account the tool call never named
  "aggregate", // D -- sliding window, sequence
  "content", // E -- content classifier at ingestion
  "envelope", // tool or amount outside the authorized task scope
  "coverage", // degradation: no manifest, no simulation, account unobserved
]);
export type CheckKind = z.infer<typeof checkKindSchema>;

/** From least to most severe. The array order IS the ordering. */
export const severitySchema = z.enum(["low", "medium", "high", "critical"]);
export type Severity = z.infer<typeof severitySchema>;

export const SEVERITIES: readonly Severity[] = severitySchema.options;

export function compareSeverity(a: Severity, b: Severity): number {
  return SEVERITIES.indexOf(a) - SEVERITIES.indexOf(b);
}

export function highestSeverity(
  severities: readonly Severity[],
): Severity | null {
  return severities.reduce<Severity | null>(
    (highest, s) =>
      highest === null || compareSeverity(s, highest) > 0 ? s : highest,
    null,
  );
}

/**
 * A finding.
 *
 * `detail` is STRUCTURED, never free text: it is what allows answering, months
 * later, exactly what fired. `explanation` is generated by an LLM after the
 * decision, for display only, and never takes part in the verdict.
 */
export interface Finding {
  readonly check: CheckKind;
  readonly severity: Severity;
  /** Stable identifier of the rule that fired. E.g. "mustNot.DELEGATE_GRANT". */
  readonly rule: string;
  readonly detail: Readonly<Record<string, unknown>>;
  readonly explanation?: string;
}

export const decisionSchema = z.enum(["allow", "flag", "deny"]);
export type Decision = z.infer<typeof decisionSchema>;

export interface Verdict {
  readonly actionId: string;
  /**
   * sha256 of the signable message this verdict is about, hex.
   *
   * A verdict with nothing tying it to specific bytes is a verdict about
   * nothing in particular: an agent can be handed "allow" for one transaction
   * and put its signature on another. Whoever signs is expected to check that
   * what it signs hashes to this. null means the bytes could not be obtained,
   * which only happens when the simulation was unavailable anyway.
   */
  readonly messageDigest: string | null;
  readonly decision: Decision;
  readonly findings: readonly Finding[];
  /** Milliseconds since the epoch. */
  readonly evaluatedAt: number;
  /**
   * Which rule set was in force. It exists to answer, months after an
   * incident, exactly which policy applied at the time.
   */
  readonly policyVersion: string;
}

/** Combination thresholds. Per customer; the verdict records the version. */
export interface Thresholds {
  /** How many `high` findings are enough for DENY. Default 2. */
  readonly highsForDeny: number;
  /** How many `medium` findings are enough for FLAG. Default 1. */
  readonly mediumsForFlag: number;
  /**
   * The most the network fee may be, in lamports.
   *
   * The fee is deliberately kept out of the effects -- it is the cost of
   * asking, not part of what was asked for -- and that is exactly why it
   * needs a bound of its own. Nothing in a manifest looks at it, so an
   * enormous priority fee is value leaving the payer that no other check
   * would ever see. Paying it to validators drains the wallet just as well as
   * paying it to an attacker.
   *
   * The default is calibration: 0.01 SOL is far above any ordinary priority
   * fee and far below an amount worth stealing.
   */
  readonly maxFeeLamports: bigint;
}

export const DEFAULT_THRESHOLDS: Thresholds = {
  highsForDeny: 2,
  mediumsForFlag: 1,
  maxFeeLamports: 10_000_000n,
};
